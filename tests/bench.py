"""300-file timing check. Run from repo root: .venv\\Scripts\\python -m tests.bench"""
import random
import re
import tempfile
from pathlib import Path

from dejavu.engine import scan

fixtures = Path(__file__).parent / "fixtures"
srcs = [p for p in fixtures.iterdir() if p.suffix in (".py", ".cpp", ".java")]
rng = random.Random(0)
tag = lambda s: "".join(chr(0xE0000 + ord(c)) for c in s)
# Every 25th file carries an AI watermark (visible, hidden, or a chat fence); the other 288 must stay unmarked.
MARKS = [lambda c: f"{c} Generated by ChatGPT\n", lambda c: f"{c} sum{tag('copilot')}\n", lambda c: "```\n"]
marked = {}

with tempfile.TemporaryDirectory() as d:
    for i in range(300):
        src = srcs[i % len(srcs)]
        text = src.read_text()
        # Worst case: every file is a renamed copy, ~6x fixture size, so most pairs overlap.
        body = "\n".join(re.sub(r"\b(n|i|x|v|count|total)\b", f"v{rng.randint(0, 99)}", text) for _ in range(6))
        name = f"s{i:03}{src.suffix}"
        if i % 25 == 0:
            body = MARKS[i // 25 % 3]("#" if src.suffix == ".py" else "//") + body
            marked[name] = i // 25 % 3
        (Path(d) / name).write_text(body, "utf-8")
    r = scan(d)

print(f'{len(r["files"])} files, {len(r["pairs"])} pairs, {len(r["marks"])} watermarked, {r["seconds"]:.2f}s')
assert len(r["files"]) == 300 and r["seconds"] < 120
kind = ["AI attribution", "hidden text (Unicode tags)", "chat code fence"]
assert {n: [x["kind"] for x in m] for n, m in r["marks"].items()} == {n: [kind[k]] for n, k in marked.items()}, r["marks"]
print("BENCH PASS")
