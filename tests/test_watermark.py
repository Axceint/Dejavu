"""AI watermark checks. Run from repo root: .venv\\Scripts\\python -m tests.test_watermark
Invisible characters are written as escapes so editors can't drop them."""
from pathlib import Path

from dejavu.engine import scan
from dejavu.watermark import watermarks

tag = lambda s: "".join(chr(0xE0000 + ord(c)) for c in s)  # "ASCII smuggling": invisible copies of ASCII letters
vs = lambda b: "".join(chr(0xFE00 + x) if x < 16 else chr(0xE0100 + x - 16) for x in b)  # bytes as variation selectors
kinds = lambda src: [(m["line"], m["kind"]) for m in watermarks(src)]

# Found
assert kinds("x = 1\n# Generated by ChatGPT\n") == [(2, "AI attribution")]
assert kinds("// written with GitHub Copilot\nint x;\n") == [(1, "AI attribution")]
assert kinds("# As an AI language model, I cannot run this.\n") == [(1, "AI attribution")]
assert kinds("// Co-authored-by: Claude <noreply@anthropic.com>\n") == [(1, "AI attribution")]
assert kinds('s = "<|endoftext|>"\n') == [(1, "LLM control token")]
assert kinds("```python\nx = 1\n```\n") == [(1, "chat code fence"), (3, "chat code fence")]
m = watermarks("x = 1  # sum" + tag("made by gpt") + "\n")
assert m == [{"line": 1, "kind": "hidden text (Unicode tags)", "text": "made by gpt"}], m
m = watermarks("a = 1\nb = 2  # " + vs("AI wrote this".encode()) + "\n")
assert m == [{"line": 2, "kind": "hidden text (variation selectors)", "text": "AI wrote this"}], m

# Not found: ordinary code and comments that only look close
for clean in ("# generated by the parser\n", "x = data[ai]\n", "# made with aiohttp\n", "# don't use an AI here\n",
              "s = '\u26a0\ufe0f done'\n",  # one selector after an emoji is how emoji pick their style
              "flag = '\U0001F3F4" + tag("gbeng") + "\U000E007F'\n",  # the England flag emoji is a tag sequence
              'def f():\n    """Example:\n    ```\n    f()\n    ```\n    """\n    return 1\n',  # fences inside a docstring
              "if (a <| b) {}\n", "// cursor created by the db driver\n"):
    assert watermarks(clean) == [], f"false mark on {clean!r}: {watermarks(clean)}"

# Demo set: exactly the two planted AI rewrites carry a watermark, one visible and one hidden
r = scan(Path(__file__).parent / "problems")
got = {n: [(x["kind"], x["text"]) for x in m] for n, m in r["marks"].items()}
assert got == {
    "grid_bfs/ai_rewrite.java": [("AI attribution", "// Generated by ChatGPT (GPT-4o), cleaned up before submitting.")],
    "two_sum/ai_rewrite.py": [("hidden text (Unicode tags)", "written by ChatGPT")],
}, got
print("WATERMARK PASS")
